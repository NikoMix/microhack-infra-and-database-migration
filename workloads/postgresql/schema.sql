CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE IF NOT EXISTS categories
(
    category_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name varchar(80) NOT NULL UNIQUE,
    parent_category_id integer NULL REFERENCES categories(category_id)
);

CREATE TABLE IF NOT EXISTS suppliers
(
    supplier_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_code varchar(20) NOT NULL UNIQUE,
    supplier_name varchar(120) NOT NULL,
    country_code char(2) NOT NULL,
    lead_time_days integer NOT NULL CHECK (lead_time_days BETWEEN 1 AND 60)
);

CREATE TABLE IF NOT EXISTS products
(
    product_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku varchar(32) NOT NULL UNIQUE,
    product_name varchar(160) NOT NULL,
    description text NOT NULL,
    category_id integer NOT NULL REFERENCES categories(category_id),
    supplier_id integer NOT NULL REFERENCES suppliers(supplier_id),
    list_price numeric(12,2) NOT NULL CHECK (list_price >= 0),
    active boolean NOT NULL DEFAULT true,
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_products_category ON products(category_id);
CREATE INDEX IF NOT EXISTS ix_products_supplier ON products(supplier_id);
CREATE INDEX IF NOT EXISTS ix_products_search_trgm
    ON products USING gin ((product_name || ' ' || description) gin_trgm_ops);

CREATE OR REPLACE FUNCTION search_products(search_text text, max_rows integer DEFAULT 20)
RETURNS TABLE
(
    sku varchar(32),
    product_name varchar(160),
    category_name varchar(80),
    supplier_name varchar(120),
    score real
)
LANGUAGE sql
STABLE
AS $$
    SELECT
        p.sku,
        p.product_name,
        c.category_name,
        s.supplier_name,
        similarity(p.product_name || ' ' || p.description, search_text) AS score
    FROM products AS p
    INNER JOIN categories AS c ON c.category_id = p.category_id
    INNER JOIN suppliers AS s ON s.supplier_id = p.supplier_id
    WHERE p.active
      AND (p.product_name || ' ' || p.description) ILIKE '%' || search_text || '%'
    ORDER BY score DESC, p.product_name
    LIMIT max_rows;
$$;
